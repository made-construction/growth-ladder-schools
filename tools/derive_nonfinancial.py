# معادلات تجميعية (COUNTIF/COUNTA) تمر على نطاق فيه صفوف مفرّغة عمداً – مراجَعة ومقبولة:
# عدد البنود الحرجة المفتوحة ونسبة اكتمال المستندات تُحسب على البنود المتبقية فقط.
ALLOW_RANGE = {('01أ', 'D25'), ('28', 'D22')}

CELL_RE = re.compile(r"(?:'((?:[^']|'')+)'|([A-Za-z0-9_؀-ۿ]+))?!?\$?([A-Z]{1,3})\$?(\d+)(?::\$?([A-Z]{1,3})\$?(\d+))?")


def code_of(name):
    return name.split(' ')[0]


def main(src, dst):
    wb = openpyxl.load_workbook(src)
    sheets = {code_of(ws.title): ws for ws in wb}
    report = []
    removed_titles = []
    for c in FIN_SHEETS:
        ws = sheets[c]
        removed_titles.append(ws.title)
        report.append(('حذف ورقة', ws.title, ''))
        wb.remove(ws)
    removed_titles_set = set(removed_titles)

    cleared = {}  # title -> set of coordinates
    for c, rng, why in CLEAR:
        ws = sheets[c]
        n = 0
        for row in ws[rng]:
            for cell in row:
                if type(cell).__name__ == 'MergedCell':
                    cleared.setdefault(ws.title, set()).add(cell.coordinate)
                    continue
                if cell.value is not None:
                    n += 1
                cell.value = None
                cleared.setdefault(ws.title, set()).add(cell.coordinate)
        report.append(('تفريغ', f'{ws.title} {rng}', f'{why} ({n} خلية)'))

    # موقع Land_Basis
    lb = wb.defined_names['Land_Basis']
    (lb_sheet, lb_ref), = list(lb.destinations)
    for c, a, val, why in SET:
        if a == 'CX':
            ws = wb[lb_sheet]
            old = ws[lb_ref.replace('$', '')].value
            ws[lb_ref.replace('$', '')].value = 'مجمع تعليمي'
            report.append(('تعديل بيانات معتمدة', f'{lb_sheet} {lb_ref} (Land_Basis)', f'«{old}» ← «مجمع تعليمي» (التصنيف المعتمد من المستثمر)'))
            continue
        ws = sheets[c]
        old = ws[a].value
        ws[a].value = val
        if why:
            report.append(('تعديل نص', f'{ws.title} {a}', why))

    # الأسماء المعرّفة المحذوفة
    drop = []
    for n, d in list(wb.defined_names.items()):
        for t, ref in d.destinations:
            coord = ref.replace('$', '')
            if t in removed_titles_set or coord in cleared.get(t, set()):
                drop.append(n)
                break
    for n in drop:
        del wb.defined_names[n]
    report.append(('حذف أسماء معرّفة', ', '.join(sorted(drop)), f'{len(drop)} اسماً'))

    # فحص: لا معادلة باقية تشير إلى ورقة محذوفة أو اسم محذوف أو خلية مفرّغة
    problems = []
    drop_set = set(drop)
    for ws in wb:
        for row in ws.iter_rows():
            for cell in row:
                v = cell.value
                if not (isinstance(v, str) and v.startswith('=')):
                    continue
                for t in removed_titles_set:
                    if t in v:
                        problems.append((ws.title, cell.coordinate, 'ورقة محذوفة', v[:120]))
                for n in drop_set:
                    if re.search(r'(?<![A-Za-z0-9_])' + re.escape(n) + r'(?![A-Za-z0-9_])', v):
                        problems.append((ws.title, cell.coordinate, 'اسم محذوف ' + n, v[:120]))
                # مراجع داخل نفس الورقة أو أوراق أخرى إلى خلايا مفرّغة
                if (code_of(ws.title), cell.coordinate) in ALLOW_RANGE:
                    continue
                for m in CELL_RE.finditer(v[1:]):
                    sheet = (m.group(1) or '').replace("''", "'") or (m.group(2) if m.group(2) and m.group(2) in wb.sheetnames else ws.title)
                    if sheet not in cleared:
                        continue
                    c1, r1 = column_index_from_string(m.group(3)), int(m.group(4))
                    c2, r2 = (column_index_from_string(m.group(5)), int(m.group(6))) if m.group(5) else (c1, r1)
                    for rr in range(r1, r2 + 1):
                        for cc in range(c1, c2 + 1):
                            if f'{get_column_letter(cc)}{rr}' in cleared[sheet]:
                                problems.append((ws.title, cell.coordinate, f'خلية مفرّغة {sheet}!{get_column_letter(cc)}{rr}', v[:120]))
                                break
                        else:
                            continue
                        break
    wb.save(dst)
    for r in report:
        print(' | '.join(r))
    if problems:
        print('\nمشكلات مراجع:')
        for p in problems:
            print(' | '.join(p))
        sys.exit(2)
    print('\nلا توجد مراجع إلى بيانات محذوفة. حُفظ:', dst)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
